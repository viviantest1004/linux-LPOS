# Everything below is a filled outline (see the top of the file for why).
# Helpers return path data; sym() wraps a list of (d, opacity) in an SVG.

DIM = ".35"


def sector(cx, cy, r0, r1, a0, a1):
    """An annular sector, angles in visual degrees (0 east, 90 north),
    swept counter-clockwise from a0 to a1. r0 = 0 gives a wedge."""
    def pt(a, r):
        t = math.radians(a)
        return cx + r * math.cos(t), cy - r * math.sin(t)
    large = 1 if (a1 - a0) % 360 > 180 else 0
    o0, o1 = pt(a0, r1), pt(a1, r1)
    f = fmt
    d = f"M{f(o0[0])} {f(o0[1])}A{f(r1)} {f(r1)} 0 {large} 0 {f(o1[0])} {f(o1[1])}"
    if r0 <= 0:
        return d + f"L{f(cx)} {f(cy)}Z"
    i0, i1 = pt(a0, r0), pt(a1, r0)
    return d + f"L{f(i1[0])} {f(i1[1])}A{f(r0)} {f(r0)} 0 {large} 1 {f(i0[0])} {f(i0[1])}Z"


def arc_stroke(cx, cy, r, w, a0, a1):
    """A round-ended stroke along a circle from a0 to a1 (visual degrees,
    counter-clockwise), as a filled outline."""
    h = w / 2

    def pt(a, rr):
        t = math.radians(a)
        return cx + rr * math.cos(t), cy - rr * math.sin(t)
    large = 1 if (a1 - a0) % 360 > 180 else 0
    o0, o1 = pt(a0, r + h), pt(a1, r + h)
    i0, i1 = pt(a0, r - h), pt(a1, r - h)
    f = fmt
    return (f"M{f(o0[0])} {f(o0[1])}A{f(r + h)} {f(r + h)} 0 {large} 0 {f(o1[0])} {f(o1[1])}"
            f"A{f(h)} {f(h)} 0 0 0 {f(i1[0])} {f(i1[1])}"
            f"A{f(r - h)} {f(r - h)} 0 {large} 1 {f(i0[0])} {f(i0[1])}"
            f"A{f(h)} {f(h)} 0 0 0 {f(o0[0])} {f(o0[1])}Z")


def seg(x0, y0, x1, y1, w):
    return Seg(x0, y0, x1, y1, w).path()


def rr(x, y, w, h, r):
    return rrect_path(x, y, w, h, r)


class Badge(str):
    """Path data for a badge (a cross, a slash) laid over an icon. The
    rest of the icon is cut back around it - see sym()."""


def sym(name, what, parts, cut=None):
    """An SVG of filled paths. A part is path data, or (data, opacity);
    data starting "evenodd:" is filled even-odd, for holes.

    `cut` is path data for a region to keep clear around a Badge: at
    16px a cross drawn straight over the Wi-Fi fan merges into it, so
    everything that is not a badge is clipped to the square minus that
    region, leaving a one-unit gap round the badge. GTK's recolouring
    forces the fill of paths, but a clip path is geometry, not paint, so
    it survives."""
    body = (f'<!-- {name} - generated by desktop/branding/src/icons.py; edit that, not this.\n'
            f'     {what} -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16">\n')
    if cut:
        body += (f'  <defs><clipPath id="cut"><path clip-rule="evenodd" '
                 f'd="M-1 -1H17V17H-1Z{cut}"/></clipPath></defs>\n')
    for p in parts:
        d, op = p if isinstance(p, tuple) else (p, None)
        clip = ' clip-path="url(#cut)"' if cut and not isinstance(d, Badge) else ""
        rule = ' fill-rule="evenodd"' if d.startswith("evenodd:") else ""
        d = d.replace("evenodd:", "")
        o = f' opacity="{op}"' if op else ""
        body += f'  <path fill="#bebebe"{rule}{o}{clip} d="{d}"/>\n'
    return body + "</svg>\n"


# Wi-Fi: a fan of three bands over a wedge, opening upwards. Levels light
# the wedge and then one band per step; the rest stay at DIM, so the
# shape of the icon never changes and only its fill does.
WIFI_C = (8, 13.5)
WIFI_SPREAD = (48.5, 131.5)
WIFI_BANDS = [(0, 3.2), (4.6, 6.6), (8.0, 10.0), (11.4, 13.4)]


def wifi(level, dim_all=False):
    cx, cy = WIFI_C
    a0, a1 = WIFI_SPREAD
    out = []
    for i, (r0, r1) in enumerate(WIFI_BANDS):
        on = (i <= level) and not dim_all
        out.append((sector(cx, cy, r0, r1, a0, a1), None if on else DIM))
    return out


def badge_x(cx, cy, s=2.2, w=1.5):
    return Badge(seg(cx - s, cy - s, cx + s, cy + s, w) + seg(cx + s, cy - s, cx - s, cy + s, w))


def x_cut(cx, cy, s=2.2, w=1.5):
    """The clear region round badge_x: its square, one unit bigger."""
    h = s + w / 2 + 1
    return rr(cx - h, cy - h, 2 * h, 2 * h, 1.5)


def wifi_icons():
    out = {}
    for lvl, name in enumerate(("weak", "ok", "good", "excellent")):
        out[f"network-wireless-signal-{name}-symbolic"] = (
            f"Wi-Fi, {name} signal.", wifi(lvl))
    out["network-wireless-signal-none-symbolic"] = ("Wi-Fi, no signal.", wifi(-1))
    out["network-wireless-symbolic"] = ("Wi-Fi.", wifi(3))
    out["network-wireless-connected-symbolic"] = ("Wi-Fi, connected.", wifi(3))
    # acquiring: the fan dimmed, and three dots where the wedge was
    acq = wifi(-1)[1:]
    for x in (4.5, 8, 11.5):
        acq.append(circle_path(x, 13.25, 1.25))
    out["network-wireless-acquiring-symbolic"] = ("Wi-Fi, connecting.", acq)
    # offline (the radio is on and nothing is joined): dim fan, a cross
    # cut into its lower right. The cut is a gap in the fan, so the cross
    # reads at 16px instead of merging into the bands.
    off = []
    for p, op in wifi(-1):
        off.append((p, op))
    off.append(badge_x(12.5, 12.5, 2.0, 1.6))
    cut = x_cut(12.5, 12.5, 2.0, 1.6)
    out["network-wireless-offline-symbolic"] = ("Wi-Fi, not connected.", off, cut)
    out["network-wireless-no-route-symbolic"] = ("Wi-Fi, no internet.", off, cut)
    # disabled (radio off): the dim fan and a slash through it, with the
    # fan cut back a unit either side of the slash
    dis = wifi(-1)
    dis.append(Badge(seg(2.5, 2.5, 13.5, 13.5, 1.6)))
    slash_cut = Seg(1.5, 1.5, 14.5, 14.5, 3.6).path()
    out["network-wireless-disabled-symbolic"] = ("Wi-Fi turned off.", dis, slash_cut)
    out["network-wireless-hardware-disabled-symbolic"] = ("Wi-Fi switched off.", dis, slash_cut)
    return out


def wired(dim=False):
    op = DIM if dim else None
    ps = [rr(5.5, 1, 5, 4.5, 1), rr(1, 10.5, 5, 4.5, 1), rr(10, 10.5, 5, 4.5, 1),
          seg(8, 5, 8, 8, 1.5), seg(3.5, 8, 12.5, 8, 1.5),
          seg(3.5, 8, 3.5, 11, 1.5), seg(12.5, 8, 12.5, 11, 1.5)]
    return [(p, op) for p in ps]


def speaker():
    # one shape: the box and the cone
    return "M1 5.5H4L8 2V14L4 10.5H1Z"


VOL_C = (6.5, 8)
VOL_WAVES = [(3.0, 4.5), (5.6, 7.1), (8.2, 9.7)]


def volume(level):
    cx, cy = VOL_C
    out = [speaker()]
    for i, (r0, r1) in enumerate(VOL_WAVES):
        on = i < level
        out.append((sector(cx, cy, r0, r1, -44, 44), None if on else DIM))
    return out


def volume_icons():
    out = {}
    for lvl, name in ((1, "low"), (2, "medium"), (3, "high")):
        out[f"audio-volume-{name}-symbolic"] = (f"Volume {name}.", volume(lvl))
    out["audio-volume-overamplified-symbolic"] = ("Volume above 100%.", volume(3))
    out["audio-volume-muted-symbolic"] = ("Sound muted.",
                                          [speaker(), badge_x(12.25, 8, 2.25, 1.6)])
    return out


# Battery: upright, like the rest of the bar's shapes. The body is a
# 1.5-unit outline; the charge is a solid block inside it with a one-unit
# gap, rising from the bottom in tenths. When charging the battery steps
# left and a bolt stands beside it, so the charge level stays as easy to
# read as when it is not.
def battery(level, charging=False, charged=False, missing=False):
    x0 = 2.5 if (charging or charged) else 4
    w = 9
    top, bot = 3, 15
    body = f"evenodd:{rr(x0, top, w, bot - top, 2)}{rr(x0 + 1.5, top + 1.5, w - 3, bot - top - 3, 0.75)}"
    nub = rr(x0 + 2.75, 1, w - 5.5, 2.5, 0.75)
    out = [body, nub]
    if missing:
        out.append(badge_x(x0 + w / 2, (top + bot) / 2, 1.9, 1.5))
        return out
    inner_top, inner_bot = top + 2.5, bot - 2.5
    h = (inner_bot - inner_top) * level / 100.0
    if level > 0:
        out.append(rr(x0 + 2.5, inner_bot - h, w - 5, h, 0.5 if h > 1 else h / 2))
    if charging or charged:
        out.append("M14.2 4.5L11.2 9.3H13.1L12.3 13.5L15.3 8.7H13.4Z")
    return out


def battery_icons():
    out = {}
    for lvl in range(0, 101, 10):
        out[f"battery-level-{lvl}-symbolic"] = (f"Battery {lvl}%.", battery(lvl))
        if lvl < 100:
            out[f"battery-level-{lvl}-charging-symbolic"] = (
                f"Battery {lvl}%, charging.", battery(lvl, charging=True))
    out["battery-level-100-charged-symbolic"] = ("Battery full, on power.",
                                                 battery(100, charged=True))
    out["battery-missing-symbolic"] = ("No battery.", battery(0, missing=True))
    out["battery-symbolic"] = ("Battery.", battery(60))
    # the older names some programs (waybar, upower) still ask for
    for legacy, lvl in (("full", 100), ("good", 70), ("low", 30), ("caution", 10), ("empty", 0)):
        out[f"battery-{legacy}-symbolic"] = (f"Battery ({legacy}).", battery(lvl))
        out[f"battery-{legacy}-charging-symbolic"] = (
            f"Battery ({legacy}), charging.", battery(lvl, charging=True))
    out["battery-full-charged-symbolic"] = ("Battery full, on power.", battery(100, charged=True))
    return out


def power():
    return [arc_stroke(8, 8.75, 5.5, 1.75, 122, 418), seg(8, 1.5, 8, 7.5, 1.75)]


def keyboard():
    body = rr(0.5, 3.5, 15, 9.5, 2)
    holes = ""
    for i in range(5):
        holes += rr(2 + i * 2.5, 5.5, 1.5, 1.5, 0.3)
    for i in range(4):
        holes += rr(3.25 + i * 2.5, 8, 1.5, 1.5, 0.3)
    holes += rr(4.5, 10.5, 7, 1, 0.3)
    return [f"evenodd:{body}{holes}"]


def brightness():
    out = [circle_path(8, 8, 3)]
    for i in range(8):
        a = math.radians(i * 45)
        out.append(seg(8 + 5.2 * math.cos(a), 8 - 5.2 * math.sin(a),
                       8 + 6.6 * math.cos(a), 8 - 6.6 * math.sin(a), 1.5))
    return out


def app_grid():
    return [circle_path(3 + 5 * c, 3 + 5 * r, 1.6) for r in range(3) for c in range(3)]


def lock():
    shackle = arc_stroke(8, 6, 3.25, 1.5, 0, 180) + seg(4.75, 6, 4.75, 7.5, 1.5) + seg(11.25, 6, 11.25, 7.5, 1.5)
    body = f"evenodd:{rr(2.5, 7, 11, 8, 1.75)}{circle_path(8, 10.5, 1.4, ccw=True)}"
    return [shackle, body]


def airplane():
    return ["M7 1.8C7 1.2 7.45 .8 8 .8S9 1.2 9 1.8V6L14.5 9.2V10.8L9 9.2V12.4L10.8 13.8V15"
            "L8 14.2L5.2 15V13.8L7 12.4V9.2L1.5 10.8V9.2L7 6Z"]


# Window buttons: the glyphs of minimise, maximise, restore and close in
# every title bar. GTK 3, GTK 4, libadwaita, libhandy and Firefox all ask
# the icon theme for these four names, so drawing them here is what makes
# the three buttons look the same in every application. 2 wide, on whole
# pixels so they are sharp at scale 1, on an 8-unit box in the middle of
# the grid, so they sit centred in the round
# buttons gtk.css draws; the strokes are separate parts because two
# overlapping subpaths of one path can cancel where they cross.
def window_icons():
    w = 2
    def ring(x, y, s, r, ri):
        return f"evenodd:{rr(x, y, s, s, r)}{rr(x + w, y + w, s - 2 * w, s - 2 * w, ri)}"
    return {
        "window-minimize-symbolic": ("Minimise a window.", [seg(5, 8, 11, 8, w)]),
        "window-maximize-symbolic": ("Maximise a window.", [ring(4, 4, 8, 2, 0.5)]),
        "window-restore-symbolic": ("Restore a maximised window.",
                                    [seg(7, 4, 12, 4, w), seg(12, 4, 12, 9, w),
                                     ring(3, 6, 7, 1.5, 0.25)]),
        "window-close-symbolic": ("Close a window.",
                                  [seg(5, 5, 11, 11, w), seg(11, 5, 5, 11, w)]),
    }


def symbolic():
    s = {}
    s.update(wifi_icons())
    s["network-wired-symbolic"] = ("Wired network.", wired())
    s["network-wired-disconnected-symbolic"] = ("Wired network, unplugged.",
                                                wired(True) + [badge_x(12.5, 3.25, 2.0, 1.5)],
                                                x_cut(12.5, 3.25, 2.0, 1.5))
    s["network-offline-symbolic"] = ("No network.", wifi(-1) + [badge_x(12.5, 12.5, 2.0, 1.6)],
                                     x_cut(12.5, 12.5, 2.0, 1.6))
    s.update(volume_icons())
    s.update(battery_icons())
    s["system-shutdown-symbolic"] = ("Power.", power())
    s["input-keyboard-symbolic"] = ("On-screen keyboard.", keyboard())
    s["display-brightness-symbolic"] = ("Brightness.", brightness())
    s["view-app-grid-symbolic"] = ("All apps.", app_grid())
    s["system-lock-screen-symbolic"] = ("Lock.", lock())
    s["airplane-mode-symbolic"] = ("Airplane mode.", airplane())
    s.update(window_icons())
    return s


