INDEX = """# index.theme - the LP icon theme. GENERATED by desktop/branding/src/icons.py.
#
# App icons are scalable SVGs drawn on a 128 grid; symbolic icons are
# scalable SVGs drawn on the 16 grid the top bar uses. Everything this
# theme does not draw is found in Papirus-Dark, which the base already
# carries and which is what the desktop used before this theme - then
# Adwaita and hicolor, which every GTK application can count on.
[Icon Theme]
Name=LP
Comment=The icons of linux-LP
Inherits=Papirus-Dark,Adwaita,hicolor
Example=utilities-terminal
Directories=scalable/apps,symbolic/status

[scalable/apps]
Context=Applications
Size=128
MinSize=16
MaxSize=512
Type=Scalable

[symbolic/status]
Context=Status
Size=16
MinSize=8
MaxSize=512
Type=Scalable
"""


def write_theme(root):
    """Write desktop/icons/LP. Stale files from an earlier run are removed
    first, so an icon dropped from the tables here is dropped on disk."""
    theme = os.path.join(root, "LP")
    apps = os.path.join(theme, "scalable", "apps")
    stat = os.path.join(theme, "symbolic", "status")
    for d in (apps, stat):
        os.makedirs(d, exist_ok=True)
        for f in os.listdir(d):
            os.unlink(os.path.join(d, f))
    with open(os.path.join(theme, "index.theme"), "w") as f:
        f.write(INDEX)
    names = {}
    for name, what, top, bottom, glyph, aliases in APPS:
        with open(os.path.join(apps, name + ".svg"), "w") as f:
            f.write(app_svg(name, what, top, bottom, glyph))
        names[name] = aliases
    # the logo is an app icon too: the installer, os-release LOGO=, the
    # app grid's "start here"
    with open(os.path.join(apps, "distributor-logo-lp.svg"), "w") as f:
        f.write(mark.svg("distributor-logo-lp.svg",
                         "The LP mark on its tile (os-release LOGO=distributor-logo-lp).",
                         (0, 0, 128, 128), mark.tile_body(uid="lg"), 128, 128))
    names["distributor-logo-lp"] = ["lp-logo", "linux-lp", "distributor-logo", "start-here",
                                    "lp", "org.lp.Welcome"]
    for name, aliases in names.items():
        for a in aliases:
            p = os.path.join(apps, a + ".svg")
            assert not os.path.exists(p), f"{a} is claimed twice"
            os.symlink(name + ".svg", p)
    for name, spec in symbolic().items():
        with open(os.path.join(stat, name + ".svg"), "w") as f:
            f.write(sym(name, *spec))
    return theme


if __name__ == "__main__":
    import sys
    write_theme(sys.argv[1] if len(sys.argv) > 1 else "../../icons")
