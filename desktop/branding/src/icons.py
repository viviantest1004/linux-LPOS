    """A sheet with its top right corner folded, as one path."""
    return _fill(f"M{x + 7} {y}H{x + w - fold}L{x + w} {y + fold}V{y + h - 7}"
                 f"a7 7 0 0 1-7 7H{x + 7}a7 7 0 0 1-7-7V{y + 7}a7 7 0 0 1 7-7Z", colour)


