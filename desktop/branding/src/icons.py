def _grad(uid, top, bottom):
    return (f'    <linearGradient id="{uid}" x1="0" y1="0" x2=".35" y2="1">\n'
            f'      <stop offset="0" stop-color="{top}"/>\n'
            f'      <stop offset="1" stop-color="{bottom}"/>\n'
            f'    </linearGradient>\n')


def tile_svg(name, what, top, bottom, glyph, rim=0.30):
    """One app icon: the tile in its two colours, the lit rim every tile
    shares, and the symbol with a soft shadow under it.

    The rim is a hairline of white along the top edge that fades out by
    the middle - how a rounded object catches light from above. It is
    what keeps a dark tile (terminal, calculator) from sinking into the
    dark dock behind it. The symbol's shadow is the symbol again, black
    at 18%, two units lower: at 48px that is under one pixel, which reads
    as the symbol sitting on the tile rather than printed into it."""
    t = TILE - 2 * INSET
    uid = name.replace(".", "_").replace("-", "_")
    body = (f'<!-- {name} - generated by desktop/branding/src/icons.py; edit that, not this.\n'
            f'     {what} -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TILE} {TILE}" width="{TILE}" height="{TILE}">\n'
            f'  <defs>\n'
            + _grad(uid + "_bg", top, bottom) +
            f'    <linearGradient id="{uid}_hl" x1="0" y1="0" x2="0" y2="1">\n'
            f'      <stop offset="0" stop-color="#fff" stop-opacity="{rim}"/>\n'
            f'      <stop offset=".5" stop-color="#fff" stop-opacity="0"/>\n'
            f'    </linearGradient>\n'
            f'    <clipPath id="{uid}_clip"><path d="{rrect_path(INSET, INSET, t, t, RADIUS)}"/></clipPath>\n'
            f'  </defs>\n'
            f'  <path fill="url(#{uid}_bg)" d="{rrect_path(INSET, INSET, t, t, RADIUS)}"/>\n')
    back = glyph.get("back")
    if back:
        body += f'  <g clip-path="url(#{uid}_clip)">\n{back(uid)}  </g>\n'
    hw = 1.5
    body += (f'  <path fill="url(#{uid}_hl)" fill-rule="evenodd" d="'
             f'{rrect_path(INSET, INSET, t, t, RADIUS)}'
             f'{rrect_path(INSET + hw, INSET + hw, t - 2 * hw, t - 2 * hw, RADIUS - hw)}"/>\n')
    if glyph.get("shadow", True):
        body += (f'  <g opacity=".18" transform="translate(0 2)">\n'
                 f'{glyph["draw"](True)}  </g>\n')
    body += glyph["draw"](False)
    body += '</svg>\n'
    return body


def _stroke(d, colour, w=PEN, extra=""):
    return (f'    <path d="{d}" fill="none" stroke="{colour}" stroke-width="{fmt(w)}" '
            f'stroke-linecap="round" stroke-linejoin="round"{extra}/>\n')


def _fill(d, colour, extra=""):
    return f'    <path d="{d}" fill="{colour}"{extra}/>\n'


def _circle(cx, cy, r, colour, extra=""):
    return f'    <circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" fill="{colour}"{extra}/>\n'


def _ring(cx, cy, r, colour, w=PEN):
    return (f'    <circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" fill="none" '
            f'stroke="{colour}" stroke-width="{fmt(w)}"/>\n')


def _rr(x, y, w, h, r, colour, extra=""):
    return _fill(rrect_path(x, y, w, h, r), colour, extra)


def _pick(sh, colour):
    """The shadow pass draws every colour black."""
    return "#000" if sh else colour


