def _gear_path(cx, cy, r_out, r_in, teeth, tooth_w, r_hole):
    """A gear as one path: the rim alternates between the tooth tops and
    the valleys, with the hole cut out by winding the other way."""
    pts = []
    n = teeth * 4
    half = math.degrees(tooth_w / 2 / r_out)
    for i in range(teeth):
        a = 360 / teeth * i
        for ang, rad in ((a - 360 / teeth / 2 + half * 1.6, r_in), (a - half, r_out),
                         (a + half, r_out), (a + 360 / teeth / 2 - half * 1.6, r_in)):
            t = math.radians(ang - 90)
            pts.append((cx + rad * math.cos(t), cy + rad * math.sin(t)))
    d = "M" + "L".join(f"{fmt(x)} {fmt(y)}" for x, y in pts) + "Z"
    return d + circle_path(cx, cy, r_hole, ccw=True)


