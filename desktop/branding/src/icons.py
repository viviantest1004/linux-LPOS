"""icons.py - the LP icon theme: app tiles for the dock, symbolic icons for the bar.

Two families with opposite jobs, so they are drawn by opposite rules.

The APP ICONS are what the owner's mockup shows down the dock: a column
of colourful rounded squares with one white symbol each. They share one
tile - the same 112-unit square with the same 26-unit corners as the LP
mark's own tile (mark.tile_body), on a 128 grid - so the logo sits in the
dock as one of the family rather than a guest. Each app gets its own hue,
light at the top left and deeper at the bottom right, which is the same
direction the light falls on the wallpaper. The symbols are drawn with
one pen: a 9-unit stroke with round ends, the ratio the mark itself uses
(its 2-unit stroke on a 14-unit height). One symbol per tile and nothing
written on it, because the dock shows these at 48 logical pixels and an
icon that needs reading at that size is a label that failed.

A hue belongs to one app. Two blue tiles side by side in a dock are the
same app to a glance, so the hues are spread round the wheel and the
neutrals (graphite, slate, paper) are kept for the tools whose real-world
object is itself neutral - a terminal, a calculator, a clock face.

The SYMBOLIC ICONS are the top bar's status icons: Wi-Fi, volume,
battery, power, the on-screen keyboard's button. GTK recolours them to
the text colour, and it does it by forcing `fill` on every path, rect and
circle in the file. So they are filled outlines only - a stroked line
would come out as a solid blob - and the "empty" part of a level icon is
the same shape at opacity .35, which GTK leaves alone. They are drawn on
the 16-unit grid with edges on half units: on the XPS the bar runs at
scale 2, where half a unit is one whole physical pixel, so every edge is
sharp there, and at scale 1 they are no softer than Adwaita's.

Names: every icon is written once under the freedesktop name the
standard gives it (utilities-terminal, accessories-calculator ...) and
then linked under the names the base's Debian applications actually ask
for (foot, org.gnome.Calculator ...) and under our own programs' names.
Links rather than copies, so an edit cannot reach one name and miss
another. Anything we do not draw falls through Inherits= to Papirus-Dark,
which the base already carries and which the desktop used before this
theme existed.
"""

import math
