def g_clock():
    def draw(sh):
        ink = _pick(sh, "#2b2f38")
        s = ""
        for i in range(12):
            a = math.radians(i * 30)
            r0 = 30 if i % 3 else 27
            s += _stroke(f"M{fmt(64 + r0 * math.sin(a))} {fmt(64 - r0 * math.cos(a))}"
                         f"L{fmt(64 + 36 * math.sin(a))} {fmt(64 - 36 * math.cos(a))}",
                         ink, 5 if i % 3 == 0 else 3, "" if i % 3 == 0 or sh else ' opacity=".55"')
        s += _stroke("M64 64L64 40", ink, 7)
        s += _stroke("M64 64L82 75", ink, 6)
        s += _stroke("M58 73L73 47", _pick(sh, mark.ORANGE_ON_LIGHT), 3)
        s += _circle(64, 64, 5, _pick(sh, mark.ORANGE_ON_LIGHT))
        return s
    return {"draw": draw, "shadow": False}


def g_calendar():
    # a page from a desk calendar: the red header is the tile's own top,
    # drawn behind the rim so the tile keeps its one silhouette
    def back(uid):
        return (f'    <path d="M0 0H128V46H0Z" fill="url(#{uid}_red)"/>\n')

    def draw(sh):
        if sh:
            return ""
        s = ""
        for x in (46, 82):
            s += _rr(x - 4, 22, 8, 16, 4, "#ffffff", ' opacity=".9"')
        grid = [(r, c) for r in range(3) for c in range(4)]
        for r, c in grid:
            x, y = 37 + c * 18, 62 + r * 16
            col = mark.ORANGE_ON_LIGHT if (r, c) == (1, 2) else "#3a3f4b"
            op = "" if (r, c) == (1, 2) else ' opacity=".7"'
            s += _rr(x - 6, y - 5, 12, 10, 3, col, op)
        return s
    return {"draw": draw, "back": back, "shadow": False}


